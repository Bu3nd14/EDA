#!/usr/bin/env python3
"""L57b: minimal ngspice-47 adaptation of TI's LM4040_NB5P0 PSpice model.

Usage: patch_lm4040_5v0.py <vendor_in.lib> <models_out.lib>

Reads the frozen vendor file, writes the patched copy.  Nothing is edited
by hand.  The same three incompatibility classes as the 4.096 V model
(L41a, vendor/voltage_reference/ti/LM4040/PROVENANCE.json), plus one
byte-level one:

 (1) ' TC=0,0' (PSpice positional tempco, all zero: a no-op) removed;
 (2) the inductor 'L_Lx1 ... 10uH' gets 'inductance=' (limitations #3);
 (3) the nested PSpice IF(...) in R_R19 becomes a nested ternary;
 (4) two non-ASCII bytes (0x96, an en-dash in 'SNOS633G-MAY 2004-REVISED')
     inside a comment line are replaced by '-': harmless to ngspice but they
     make the file invalid UTF-8.
A 4-line header of our own is prepended (comment lines only).
"""
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
raw = open(src, "rb").read()
text = raw.decode("latin-1")

n_tc = text.count(" TC=0,0")
text = text.replace(" TC=0,0", "")

old_l = "L_Lx1         N01136 V+  10uH"
assert text.count(old_l) == 1
text = text.replace(old_l, "L_Lx1         N01136 V+  inductance=10uH")

old_if = "{IF({TOL}==0,162223.6,IF({TOL}>0,161865.5, 162581.7 ))}"
assert text.count(old_if) == 1
new_if = "{(({TOL})==0) ? 162223.6 : ((({TOL})>0) ? 161865.5 : 162581.7)}"
text = text.replace(old_if, new_if)

n_hi = len(re.findall(r"[\x80-\xff]", text))
text = re.sub(r"[\x80-\xff]", "-", text)

hdr = (
    "* ngspice-47 adaptation of TI LM4040_NB5P0_TRANS.lib (SNOM508.ZIP) - L57b.\n"
    "* Generated by docs/preamp/data/2026-10-25/L57b/script/patch_lm4040_5v0.py;\n"
    "* see lm4040_5v0_ngspice.provenance.json for the exact list of changes.\n"
    "* Original TI text follows unchanged apart from those changes.\n"
)
open(dst, "w", newline="").write(hdr + text)
print(f"removed TC=0,0 x{n_tc}; inductance= x1; IF->ternary x1; non-ascii bytes replaced x{n_hi}")
