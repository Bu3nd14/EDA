#!/usr/bin/env python3
"""L70: the netlists of the two simplifications, from COPIES of circuits/preamp/psu.py.

Each variant is psu.py with a few exact text replacements (each must occur once, or the script
refuses), run with the SKiDL venv and PSU_NET_OUT into this folder:

  oggi   no change: must give circuits/preamp/psu.net back (the check below);
  s2     the mains detector gone (S2): Q504, R510, R554, R511, R512, R555, C518 and the three
         diodes D533 / D534 / D535 from its channel AT_MD. The - inputs of U506 A and U513 D go to
         RLY_RET (VREF on +): both idle released, as the channels of a
         circuit without the detector; R569 stays (AT_MD would float on a bench; on the board the
         channels are idle and their pins tied, so the FMEA counts R569 as gone);
  s1     the latch after a rail fault gone (S1): Q513, Q514, R582, R583, R584, C554, C555. The
         latch's trigger network (R580 / C552 / D541 = AT_T2S, R581 / C553 / R585 = AT_F, U515 C / D)
         loads nothing without R582 and stays on the bench as inert parts (no floating node); the
         FMEA counts it as gone. The fuses are NOT parts here: position A is T1's secondary current,
         i(vt1a_sns) / i(vt1b_sns) (--sonda-t2), position B is R550 / R551's current, from their
         voltages: the opening is judged from the I2t afterwards, not modelled;
  s1s2   both.

    /usr/bin/python3 -I fai_varianti.py
writes psu_<v>.py and psu_<v>.net here, and varianti.txt (the parts of each netlist against oggi).
"""
import os
import re
import subprocess
import sys

QUI = os.path.dirname(os.path.abspath(__file__))
REPO = QUI
for _ in range(6):
    REPO = os.path.dirname(REPO)
SRC = os.path.join(REPO, "circuits", "preamp", "psu.py")
NET = os.path.join(REPO, "circuits", "preamp", "psu.net")
VENV = "/Users/roberto/EDA/env/venv/bin/python3"
assert os.path.exists(SRC) and os.path.exists(NET), (SRC, NET)

S2 = [
    ('''    res("11k", "R510", RECT_V, MB_R)
    res("11k", "R554", MB_R, MB)
    res("4.7k", "R511", MB, RET)          # on above ~4 V of RECT_V
    qd = part("Transistor_BJT", "BC847", "BC847", "Q504", FP_SOT23)
    qd[1] += MB
    qd[2] += RET
    qd[3] += MD
''', '''    # L70 S2: the detector gone (U506 A and U513 D idle, released: their - inputs on RLY_RET)
'''),
    ('''    cmp2["2"] += MD        # A -: out LOW when MD > VREF (no mains)
''', '''    cmp2["2"] += RET       # L70 S2: idle
'''),
    ('''                  (VREF, MD, AT_MD)))         # no half-wave for ~15 ms
''', '''                  (VREF, RET, AT_MD)))        # L70 S2: idle
'''),
    ('''    res(R_MD_HALF, "R512", V5, MD_R)
    res(R_MD_HALF, "R555", MD_R, MD)
    cap(C_MD, "C518", MD, RET, FP_C1206)   # ADR-108: C0G 100 nF only from 1206 up
''', ""),
    ('''    diode("BAT54", "D533", AT_PG, AT_MD)
''', ""),
    ('''    diode("BAS416", "D534", AT_F, AT_MD)
''', ""),
    ('''    diode("BAS416", "D535", AT_T2S, AT_MD)
''', ""),
]
S1 = [
    ('''    res("47k", "R582", AT_F, AT_BN)
''', ""),
    ('''    q = part("Transistor_BJT", "BC847", "BC847", "Q513", FP_SOT23)
    q[1] += AT_BN                  # B
    q[2] += RET                    # E
    q[3] += AT_BP                  # C
    res("100k", "R583", AT_BN, RET)
    cap("1n", "C554", AT_BN, RET)
    q = part("Transistor_BJT", "BC857", "BC857", "Q514", FP_SOT23)
    q[1] += AT_BP                  # B
    q[2] += AT_ON                  # E
    q[3] += AT_BN                  # C
    res("100k", "R584", AT_ON, AT_BP)
    cap("1n", "C555", AT_ON, AT_BP)
''', "    # L70 S1: the latch gone (Q513, Q514, R582-R584, C554, C555)\n"),
]
VARIANTI = {"oggi": [], "s2": S2, "s1": S1, "s1s2": S2 + S1}


def refs(path):
    return set(re.findall(r'\(comp\b\s*\(ref "([^"]+)"\)', open(path).read()))


def corpo(path):
    # the netlist without its header (date, tool, source path)
    # and without SKiDL's pointers to the source's file and line, which differ by construction
    t = open(path).read()
    t = t[t.index("(components"):]
    t = re.sub(r'\(source "[^"]*"\)', "", t)
    return re.sub(r'"SKiDL Line"\) "[^"]*"', '"SKiDL Line")', t)


src = open(SRC).read()
# the copy sits elsewhere: its own folder on sys.path is harmless (psu.py imports only skidl), and
# REPO is used only for the default PSU_NET_OUT, which is always set here
righe = []
base = refs(NET)
for v, sost in VARIANTI.items():
    t = src
    for a, b in sost:
        n = t.count(a)
        if n != 1:
            raise SystemExit("RIFIUTATO: %s, un testo trovato %d volte:\n%s" % (v, n, a))
        t = t.replace(a, b)
    py = os.path.join(QUI, "psu_%s.py" % v)
    out = os.path.join(QUI, "psu_%s.net" % v)
    open(py, "w").write("# L70 variant %s, GENERATED by fai_varianti.py from circuits/preamp/psu.py\n" % v + t)
    env = dict(os.environ, PSU_NET_OUT=out)
    r = subprocess.run([VENV, py], cwd=QUI, env=env, capture_output=True, text=True)
    if r.returncode != 0 or not os.path.exists(out):
        sys.stdout.write(r.stdout + r.stderr)
        raise SystemExit("RIFIUTATO: %s non genera" % v)
    x = refs(out)
    righe.append("%s: %d parti; tolte %s; aggiunte %s" % (
        v, len(x), " ".join(sorted(base - x)) or "-", " ".join(sorted(x - base)) or "-"))
    if v == "oggi" and corpo(out) != corpo(NET):
        raise SystemExit("RIFIUTATO: la variante oggi non ridà circuits/preamp/psu.net")
righe.append("oggi: il corpo del netlist (da \"(components\") uguale a circuits/preamp/psu.net")
open(os.path.join(QUI, "varianti.txt"), "w").write("\n".join(righe) + "\n")
print("\n".join(righe))
